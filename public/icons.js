/** Replace every <i data-ic="name"></i> placeholder under root with its SVG. */
export function hydrateIcons(root = document) {
  root.querySelectorAll('i[data-ic]').forEach((el) => { el.outerHTML = ic(el.dataset.ic); });
}

/** Set a button's icon + label (label may be empty for icon-only buttons). */
export function setBtn(btn, icon, label, color) {
  btn.innerHTML = `${ic(icon)}${label ? `<span>${label}</span>` : ''}`;
  if (color !== undefined) {
    btn.className = btn.className.replace(/\bc-\w+\b|\bsolid-\w+\b|\bprimary\b/g, '').trim();
    if (color) btn.classList.add(color);
  }
}
